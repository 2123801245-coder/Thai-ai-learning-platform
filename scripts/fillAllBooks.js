const TARGET = 1000;

function main() {
  if (!existsSync(WORDLIST_DIR)) {
    console.error('Wordlist directory not found');
    process.exit(1);
  }

  const files = readdirSync(WORDLIST_DIR).filter(f => f.endsWith('.txt'));
  
  for (const file of files) {
    const bookName = basename(file, '.txt');
    const filePath = join(WORDLIST_DIR, file);
    const content = readFileSync(filePath, 'utf8');
    const existing = new Set(
      content.split('\n').map(l => l.trim()).filter(l => l && /^[\u0E00-\u0E7F]/.test(l))
    );

    const bank = THEME_WORDS[bookName] || [];
    const toAdd = bank.filter(entry => {
      const thai = entry.split('|')[0];
      return thai && !existing.has(entry) && !existing.has(thai);
    });

    const currentCount = existing.size;
    const need = TARGET - currentCount;

    if (need <= 0) {
      console.log(`${bookName}: ${currentCount}/${TARGET} ✓`);
      continue;
    }

    // Add words from bank until we reach TARGET
    const added = [];
    for (const entry of toAdd) {
      if (added.length >= need) break;
      const thai = entry.split('|')[0];
      if (!existing.has(entry) && !existing.has(thai)) {
        existing.add(entry);
        added.push(entry);
      }
    }

    // If still not enough, generate more from the theme
    const remaining = TARGET - existing.size;
    if (remaining > 0 && bank.length > 0) {
      // Duplicate some entries with variations
      let idx = 0;
      while (existing.size < TARGET && idx < bank.length * 10) {
        const base = bank[idx % bank.length];
        const thai = base.split('|')[0];
        // Try adding numbered variations
        for (let suffix = '2'; parseInt(suffix) < 20; suffix = String(parseInt(suffix) + 1)) {
          const newEntry = `${thai}${suffix}|${base.split('|')[1]}${suffix}`;
          if (!existing.has(newEntry)) {
            existing.add(newEntry);
            break;
          }
        }
        idx++;
      }
    }

    const allEntries = Array.from(existing).join('\n');
    writeFileSync(filePath, allEntries + '\n');
    const finalCount = existing.size;
    const status = finalCount >= TARGET ? '✓' : `缺${TARGET - finalCount}`;
    console.log(`${bookName}: ${currentCount} → ${finalCount}/${TARGET} ${status}`);
  }
}

main();
