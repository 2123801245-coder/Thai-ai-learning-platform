// ============================================================
function main() {
  console.log('📖 读取词库...');
  const content = readFileSync('src/data/vocabAllBooks.js', 'utf8');
  const match = content.match(/export const vocabAllBooks = (\[[\s\S]*?\]);/);
  let data = JSON.parse(match[1]);

  console.log(`📊 原始词条: ${data.length}`);

  // Step 1: 清理颜色词书 — 删除所有垃圾数据，只保留干净颜色
  const colorGarbage = data.filter(e => e.category === '颜色');
  const nonColor = data.filter(e => e.category !== '颜色');

  // 重建干净颜色词书
  const cleanColorEntries = CLEAN_COLORS.map((c, i) => ({
    word: c.word,
    pronunciation: c.pron,
    meaning: c.meaning,
    pos: c.pos,
    example_thai: c.ex_t,
    example_chinese: c.ex_c,
    category: '颜色',
    difficulty: i < 15 ? 'beginner' : (i < 35 ? 'intermediate' : 'advanced'),
    verified: true,
    review_status: 'verified',
    source: 'clean-colors',
  }));

  console.log(`🎨 颜色: ${colorGarbage.length} → ${cleanColorEntries.length} (清理垃圾)`);

  // Step 2: 添加专业词书
  function makeEntries(words, category, baseDiff) {
    return words.map((w, i) => {
      let diff = baseDiff;
      if (i < words.length * 0.3) diff = 'beginner';
      else if (i < words.length * 0.7) diff = 'intermediate';
      else diff = 'advanced';

      return {
        word: w[0],
        pronunciation: w[1],
        meaning: w[2],
        pos: w[3],
        example_thai: w[4],
        example_chinese: w[5],
        category,
        difficulty: diff,
        verified: true,
        review_status: 'verified',
        source: 'professional-v1',
      };
    });
  }

  const medicalEntries = makeEntries(MEDICAL_WORDS, '医疗泰语', 'intermediate');
  const legalEntries = makeEntries(LEGAL_WORDS, '法律泰语', 'advanced');
  const techEntries = makeEntries(TECH_WORDS, '科技泰语', 'intermediate');
  const businessEntries = makeEntries(BUSINESS_WORDS, '商务泰语', 'intermediate');

  console.log(`🏥 医疗: ${medicalEntries.length}`);
  console.log(`⚖️  法律: ${legalEntries.length}`);
  console.log(`💻 科技: ${techEntries.length}`);
  console.log(`💼 商务: ${businessEntries.length}`);

  // Step 3: 合并
  const allData = [
    ...nonColor,
    ...cleanColorEntries,
    ...medicalEntries,
    ...legalEntries,
    ...techEntries,
    ...businessEntries,
  ];

  // Step 4: 去重（按 category + word）
  const seen = new Set();
  const deduped = allData.filter(e => {
    const key = `${e.category}|${e.word}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });

  console.log(`\n📊 最终: ${deduped.length} 条`);

  // Stats
  const stats = {};
  deduped.forEach(e => {
    if (!stats[e.category]) stats[e.category] = { count: 0, beginner: 0, intermediate: 0, advanced: 0 };
    stats[e.category].count++;
    stats[e.category][e.difficulty]++;
  });

  console.log('─'.repeat(65));
  Object.entries(stats).sort((a, b) => b[1].count - a[1].count).forEach(([cat, s]) => {
    console.log(`${cat.padEnd(14)} | ${String(s.count).padStart(4)} | 初:${String(s.beginner).padStart(3)} 中:${String(s.intermediate).padStart(3)} 高:${String(s.advanced).padStart(3)}`);
  });
  console.log('─'.repeat(65));

  // Write
  const output = `// 自动生成 - 泰语词库 v4 (清理垃圾+专业词书)
// 生成时间: ${new Date().toISOString()}
// 共 ${deduped.length} 条词条

export const vocabAllBooks = ${JSON.stringify(deduped, null, 0)};

// 词书统计
export const BOOK_STATS = ${JSON.stringify(stats, null, 2)};
`;

  writeFileSync('src/data/vocabAllBooks.js', output, 'utf8');
  console.log(`\n✅ 已写入 src/data/vocabAllBooks.js`);
}

main();
