function makeWord(book, base, index) {
  const [thai, pronunciation, meaning, partOfSpeech] = base;
  const template = templates[index % templates.length];
  return {
    id: `expanded-${book}-${String(index + 1).padStart(4, "0")}`,
    thai_word: thai,
    pronunciation,
    chinese_meaning: meaning,
    part_of_speech: partOfSpeech,
    category: book,
    book,
    difficulty: "advanced",
    example_thai: template([thai]),
    example_chinese: `这个词用于${topics[book]}。`
  };
}

