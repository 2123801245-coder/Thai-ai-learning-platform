export const getCategory = (id) =>
  mediaCategories.find((c) => c.id === id) || null;

export const getLessonById = (id) =>
  mediaLessons.find((l) => l.id === id) || null;

export const getLessonsByType = (type) =>
  type && type !== "all"
    ? mediaLessons.filter((l) => l.type === type)
    : mediaLessons;

/** 分类计数（列表页筛选用） */
export function getMediaStats() {
  const byType = {};
  for (const lesson of mediaLessons) {
    byType[lesson.type] = (byType[lesson.type] || 0) + 1;
  }
  const totalMinutes = mediaLessons.reduce((sum, l) => sum + (l.minutes || 0), 0);
  return {
    total: mediaLessons.length,
    categories: mediaCategories.length,
    totalMinutes,
    byType,
  };
}

