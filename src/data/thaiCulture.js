/* 分类取数工具 */
export function getCultureByCategory(categoryId) {
  if (!categoryId || categoryId === "all") return culturePoints;
  return culturePoints.filter((p) => p.category === categoryId);
}

export function getCultureStats() {
  return cultureCategories.map((c) => ({
    ...c,
    count: culturePoints.filter((p) => p.category === c.id).length,
  }));
}
